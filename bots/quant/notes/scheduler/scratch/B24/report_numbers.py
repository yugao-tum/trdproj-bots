import json,collections,pandas as pd,numpy as np,re
E=json.load(open('/tmp/opencode/cricket_events.json'))
C=json.load(open('/tmp/opencode/cand2.json'))
Mm=json.load(open('/tmp/opencode/matched.json')); MP=[m for m in Mm if m.get('match')]
P=json.load(open('/tmp/opencode/price_raw.json'))
T=pd.read_csv('priced.csv'); M=pd.read_csv('clean_matches.csv'); B=pd.read_csv('bets_final_1c.csv'); H=pd.read_csv('bets_posthoc_balanced.csv')
print('gamma events fetched',len(E))
print('T20 moneyline markets (unique conditionId)',len(set(c['cid'] for c in C)))
print('by month',dict(sorted(collections.Counter(c['date'][:7] for c in C).items())))
print('matched to Cricsheet',len(MP),'unique Cricsheet files',len(set(m['match']['file'] for m in MP)))
print('price records',len(P),'with pre-match trade',sum(1 for p in P if p.get('last')))
print('unique priced matches',T.match.nunique(),'outcome rows',len(T))
print('clean matches (decisive, both sides, |sum-1|<=0.10)',len(M))
print('clean by src',M.groupby('src').size().to_dict())
print('clean by year',M.date.str[:4].value_counts().sort_index().to_dict())
print('stale hours q50/q75/q90/q95/q99',P and T.stale_h.quantile([.5,.75,.9,.95,.99]).round(3).to_dict())
print('50-50/no-result excluded: 6; one-sided/missing: 1; both-side sum>0.10: 4')
print('MODEL ll %.4f brier %.4f'%(-np.mean(M.y0*np.log(M.m0)+(1-M.y0)*np.log(1-M.m0)),np.mean((M.m0-M.y0)**2)))
print('MARKET ll %.4f brier %.4f'%(-np.mean(M.y0*np.log(M.p0)+(1-M.y0)*np.log(1-M.p0)),np.mean((M.p0-M.y0)**2)))
print('CONST ll %.4f'%(-np.mean(M.y0*np.log(M.y0.mean())+(1-M.y0)*np.log(1-M.y0.mean()))))
print('bets',len(B),'net mean %.4f'%B.net.mean(),'total %.2f'%B.net.sum(),'win %.3f'%B.y.mean(),'mean entry %.3f'%B.p.mean())
print('zero-fee, half1c net mean %.4f'%(B.y-(B.p+0.01)).mean())
print('zero-fee, half0 net mean %.4f'%(B.y-B.p).mean())
print('posthoc balanced',len(H),'net mean %.4f'%H.net.mean(),'total %.2f'%H.net.sum(),'win %.3f'%H.y.mean())
print('posthoc by year',H.groupby(H.date.str[:4]).net.agg(['size','mean']).round(3).to_dict())
print('posthoc by src',H.groupby('src').net.agg(['size','mean']).round(3).to_dict())
